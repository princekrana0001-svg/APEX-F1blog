/* ==================================================
   GET ARTICLE ID
================================================== */

const articleId =
    window.location.hash.substring(1);


/* ==================================================
   GET HTML ELEMENTS
================================================== */

const articleCategory =
    document.getElementById("articleCategory");

const articleTitle =
    document.getElementById("articleTitle");

const articleImage =
    document.getElementById("articleImage");

const articleReadTime =
    document.getElementById("articleReadTime");

const articleContent =
    document.getElementById("articleContent");


/* ==================================================
   LOAD ARTICLE
================================================== */

function loadArticle() {


    const article =
        blogArticles[articleId];


    /* ==================================================
       CHECK ARTICLE
    ================================================== */

    if (!article) {

        articleCategory.textContent =
            "APEX F1";

        articleTitle.textContent =
            "Article Not Found";

        articleReadTime.textContent =
            "";


        articleContent.innerHTML = `

            <p class="article-intro">
                Sorry, the requested article could not be found.
            </p>

            <p>
                Please return to the blogs page and select an article.
            </p>

            <a
                href="blogs.html"
                class="all-blogs-button">

                BACK TO BLOGS →

            </a>

        `;

        return;

    }


    /* ==================================================
       SET CATEGORY
    ================================================== */

    articleCategory.textContent =
        article.category;


    /* ==================================================
       SET TITLE
    ================================================== */

    articleTitle.textContent =
        article.title;


    /* ==================================================
       SET IMAGE
    ================================================== */

    articleImage.src =
        article.image;

    articleImage.alt =
        article.title;


    /* ==================================================
       SET READ TIME
    ================================================== */

    articleReadTime.textContent =
        article.readTime;


    /* ==================================================
       SET BROWSER TITLE
    ================================================== */

    document.title =
        article.title + " | APEX F1";


    /* ==================================================
       CLEAR OLD CONTENT
    ================================================== */

    articleContent.innerHTML = "";


    /* ==================================================
       ADD PARAGRAPHS
    ================================================== */

    article.paragraphs.forEach(
        function (paragraph, index) {


            /* First paragraph */

            if (index === 0) {

                const intro =
                    document.createElement("p");

                intro.className =
                    "article-intro";

                intro.textContent =
                    paragraph;

                articleContent.appendChild(
                    intro
                );

            }


            else {


                /* Add heading */

                if (index === 2) {

                    const heading =
                        document.createElement("h2");

                    heading.textContent =
                        "Understanding the Story";

                    articleContent.appendChild(
                        heading
                    );

                }


                const paragraphElement =
                    document.createElement("p");

                paragraphElement.textContent =
                    paragraph;

                articleContent.appendChild(
                    paragraphElement
                );

            }

        }
    );


    /* ==================================================
       ARTICLE ENDING
    ================================================== */

    const ending =
        document.createElement("div");

    ending.className =
        "article-ending";


    const endingText =
        document.createElement("p");

    endingText.textContent =
        "Formula 1 continues to evolve as technology, strategy and human skill shape the future of the sport.";


    ending.appendChild(
        endingText
    );


    articleContent.appendChild(
        ending
    );

}


/* ==================================================
   START
================================================== */

loadArticle();